export function isHolidayYearCovered(year: number): boolean {
  return year >= HOLIDAY_YEAR_FROM && year <= HOLIDAY_YEAR_TO;
}

export function holidayNameOn(date: Date): string | null {
  return KR_HOLIDAYS[formatDate(date)] ?? null;
}

export function isHoliday(date: Date): boolean {
  return holidayNameOn(date) !== null;
}

export function isWeekend(date: Date): boolean {
  const dow = date.getDay();
  return dow === 0 || dow === 6;
}

export function isNonWorkday(date: Date): boolean {
  return isWeekend(date) || isHoliday(date);
}

export function nextBizDay(date: Date): Date {
  const next = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  while (isNonWorkday(next)) next.setDate(next.getDate() + 1);
  return next;
}

export function holidaysInMonth(year: number, month: number): Record<number, string> {
  const found: Record<number, string> = {};
  const lastDate = new Date(year, month + 1, 0).getDate();
  for (let day = 1; day <= lastDate; day += 1) {
    const name = KR_HOLIDAYS[formatDate(new Date(year, month, day))];
    if (name) found[day] = name;
  }
  return found;
}
